import { chromium } from 'playwright';
const browser = await chromium.launch();
const context = await browser.newContext({ viewport: { width: 430, height: 900 }, deviceScaleFactor: 2 });
const page = await context.newPage();
await page.goto('http://127.0.0.1:3000?lat=50.76&lon=-1.2&z=11', { waitUntil: 'domcontentloaded' });
await page.evaluate(() => localStorage.clear());
await page.reload({ waitUntil: 'domcontentloaded' });
await page.waitForSelector('.leaflet-container');
await page.waitForTimeout(3000);
await page.locator('.menu-button').click();
await page.waitForTimeout(400);
await page.screenshot({ path: 'artifacts/layer-menu-final.png' });
await page.locator('.menu-panel').evaluate((el) => el.querySelector('.menu-body').scrollTo(0, 640));
await page.waitForTimeout(300);
await page.screenshot({ path: 'artifacts/layer-menu-overlays.png' });
await browser.close();
