#!/usr/bin/env node
/**
 * Write src/lib/lightCoverage.generated.ts from the light datasets in public/.
 *
 * The chart fetches a regional light dataset only when the view reaches its
 * coverage box, so those boxes have to follow the data. Hand-written boxes go
 * stale the moment a dataset is rebuilt; these are derived from the files that
 * are actually shipped, and `npm run build` regenerates them.
 *
 *   npm run lights:bounds
 *
 * Output is deterministic: the same datasets always produce the same file, so
 * an unchanged rebuild leaves the working tree clean.
 */
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const publicDir = resolve(root, 'public');
const outFile = resolve(root, 'src/lib/lightCoverage.generated.ts');

/** Two decimals, rounded outward: a coverage box may never be smaller than its data. */
const floor2 = (value) => Math.floor(value * 100) / 100;
const ceil2 = (value) => Math.ceil(value * 100) / 100;

function extent(records, projectLon) {
  let south = Infinity;
  let north = -Infinity;
  let west = Infinity;
  let east = -Infinity;
  for (const record of records) {
    if (!Number.isFinite(record.lat) || !Number.isFinite(record.lon)) continue;
    const lon = projectLon(record.lon);
    south = Math.min(south, record.lat);
    north = Math.max(north, record.lat);
    west = Math.min(west, lon);
    east = Math.max(east, lon);
  }
  if (!Number.isFinite(south) || !Number.isFinite(west)) return null;
  return [floor2(south), floor2(west), ceil2(north), ceil2(east)];
}

function coverageBounds(records) {
  const plain = extent(records, (lon) => lon);
  if (!plain) return null;
  // A volume crossing the antimeridian has a huge span in ordinary -180..180
  // degrees (volume 06 measures -177..179, which would also cover the whole
  // Atlantic). Measuring it with its eastern half shifted west gives the
  // compact Pacific form (-215..-116); boundsIntersect compares modulo 360.
  const pacific = extent(records, (lon) => (lon > 0 ? lon - 360 : lon));
  const span = (box) => box[3] - box[1];
  return pacific && span(pacific) < span(plain) ? pacific : plain;
}

async function readRecords(file) {
  let raw;
  try {
    raw = await readFile(resolve(publicDir, file), 'utf8');
  } catch {
    throw new Error(`missing public/${file} — run the light data build before this`);
  }
  return JSON.parse(raw).records ?? [];
}

const volumeFiles = (await readdir(publicDir))
  .filter((name) => /^uscg-lights-\d+\.json$/.test(name))
  .sort();
if (!volumeFiles.length) throw new Error('no uscg-lights-<volume>.json files in public/');

const volumes = [];
const boundsByVolume = new Map();
for (const file of volumeFiles) {
  const volume = file.match(/uscg-lights-(\d+)\.json/)[1];
  const bounds = coverageBounds(await readRecords(file));
  if (!bounds) throw new Error(`${file} holds no usable records`);
  volumes.push(volume);
  boundsByVolume.set(volume, bounds);
}

const ccgBounds = coverageBounds(await readRecords('ccg-lights.json'));
if (!ccgBounds) throw new Error('ccg-lights.json holds no usable records');

const box = (value) => `[${value.join(', ')}]`;

const output = [
  '// Generated by scripts/build-light-bounds.mjs — do not edit by hand.',
  '// Run `npm run lights:bounds`; `npm run build` does it for you.',
  "import type { Bounds } from './geo';",
  '',
  '/** USCG Light List volumes shipped in public/, in volume order. */',
  `export const USCG_VOLUMES: string[] = [${volumes.map((volume) => `'${volume}'`).join(', ')}];`,
  '',
  '/**',
  ' * Where each volume reaches, as the outward-rounded extents of its records.',
  ' * A volume whose data crosses the antimeridian is written in the compact',
  ' * Pacific frame (e.g. -215..-116); boundsIntersect compares modulo 360.',
  ' */',
  'export const USCG_VOLUME_BOUNDS: Record<string, Bounds[]> = {',
  ...volumes.map((volume) => `  '${volume}': [${box(boundsByVolume.get(volume))}],`),
  '};',
  '',
  '/** Extent of the whole CCG supplement, across all four Canadian volumes. */',
  `export const CCG_COVERAGE: Bounds = ${box(ccgBounds)};`,
  '',
];

await writeFile(outFile, output.join('\n'), 'utf8');

console.log(`[light-bounds] ${volumes.length} USCG volumes + CCG coverage -> src/lib/lightCoverage.generated.ts`);
for (const volume of volumes) console.log(`  ${volume}: ${box(boundsByVolume.get(volume))}`);
console.log(`  ccg: ${box(ccgBounds)}`);
