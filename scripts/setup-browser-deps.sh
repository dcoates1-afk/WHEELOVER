#!/usr/bin/env bash
# Prepare headless Chromium on a minimal Linux container without root.
#
#   ./scripts/setup-browser-deps.sh
#   source scripts/browser-env.sh && node scripts/verify-ui.mjs
#
# Extracts the shared libraries Chromium needs (libnss3, libnspr4, libatk*, libx*)
# into .browser-deps/ and copies DejaVu fonts into the user font path, so text —
# including the WHEELOVER wordmark the UI checks measure — actually renders.
# Re-run after a workspace restore; nothing outside the workspace is changed.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
PREFIX="$ROOT/.browser-deps"
LIBDIR="$PREFIX/root/usr/lib/x86_64-linux-gnu"
FONTDIR="${XDG_DATA_HOME:-$HOME/.local/share}/fonts"

PACKAGES=(
  libnspr4 libnss3 libatk1.0-0t64 libatk-bridge2.0-0t64 libatspi2.0-0t64
  libxcomposite1 libxdamage1 libxfixes3 libxrandr2 libxrender1 libxkbcommon0
  libasound2t64 libdbus-1-3 libx11-6 libxcb1 libxext6 libxi6 libxtst6
  libglib2.0-0t64 fonts-dejavu-core fonts-dejavu-mono
  # Chromium 156 (Playwright 1.64) links cups, cairo and pango, and pango
  # pulls fontconfig, harfbuzz, freetype and their own dependencies. Earlier
  # Chromium builds did not, so a list that stops at the X/NSS libraries leaves
  # the browser unable to start. apt-get download resolves no dependencies, so
  # they are all named here.
  libcups2t64 libavahi-common3 libavahi-client3
  libcairo2 libpixman-1-0 libxcb-render0 libxcb-shm0
  libpango-1.0-0 libpangoft2-1.0-0 libpangocairo-1.0-0
  libfontconfig1 libfreetype6 libharfbuzz0b libgraphite2-3 libfribidi0
  libthai0 libdatrie1 libpng16-16t64 libbrotli1 libexpat1 libbz2-1.0 libuuid1
)

mkdir -p "$PREFIX/debs" "$PREFIX/apt/lists/partial" "$PREFIX/apt/archives/partial" "$FONTDIR"

APT_OPTS=(
  -o Dir::State::lists="$PREFIX/apt/lists"
  -o Dir::Cache="$PREFIX/apt"
  -o Debug::NoLocking=1
)

if [ ! -d "$PREFIX/apt/lists" ]; then
  echo "no package index; refreshing into $PREFIX/apt" >&2
fi
apt-get "${APT_OPTS[@]}" update >/dev/null

cd "$PREFIX/debs"
apt-get "${APT_OPTS[@]}" download "${PACKAGES[@]}" >/dev/null
for deb in ./*.deb; do dpkg-deb -x "$deb" "$PREFIX/root"; done

find "$PREFIX/root/usr/share/fonts" -name '*.ttf' -exec sh -c '
  target=$1; shift
  for file do
    [ -e "$target/$(basename "$file")" ] || cp "$file" "$target/"
  done
' sh "$FONTDIR" {} +

cat > "$ROOT/scripts/browser-env.sh" <<ENV
# Generated by scripts/setup-browser-deps.sh
export LD_LIBRARY_PATH="$LIBDIR\${LD_LIBRARY_PATH:+:\$LD_LIBRARY_PATH}"
ENV

echo "shared libraries: $LIBDIR"
echo "fonts: $(find "$FONTDIR" -name '*.ttf' | wc -l) in $FONTDIR"
echo "now run: source scripts/browser-env.sh"
